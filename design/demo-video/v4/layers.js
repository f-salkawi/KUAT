const { chromium } = require('playwright-core')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome', headless: true })
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
  await p.goto('http://127.0.0.1:8077/#/')
  await p.waitForFunction(() => document.querySelector('.stage'))
  await p.evaluate(() => { const s = document.querySelector('.stage'); if (s.classList.contains('closed')) s.querySelector('.layer.cream').dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })) })
  await p.mouse.click(720, 450).catch(() => {})
  await p.waitForFunction(() => document.querySelector('.stage')?.classList.contains('open'), null, { timeout: 15000 })
  await p.waitForTimeout(2500)
  const r = await p.evaluate(() => [...document.querySelectorAll('.layer')].map((e) => { const b = e.getBoundingClientRect(); return { x: b.x, y: b.y, width: b.width, height: b.height } }))
  console.log(JSON.stringify(r))
  await b.close()
})()
